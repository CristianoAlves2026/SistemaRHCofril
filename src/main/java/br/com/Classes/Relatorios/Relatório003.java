private void gerarRelatorioPDF(String caminhoDestino, String statusFiltro, java.util.List<Integer> idsEmpresas) {
        // Criação do documento A4
        com.lowagie.text.Document documento = new com.lowagie.text.Document(com.lowagie.text.PageSize.A4);

        try {
            com.lowagie.text.pdf.PdfWriter.getInstance(documento, new java.io.FileOutputStream(caminhoDestino));
            documento.open();

            // --- 1. CONFIGURAÇÃO DA PALETA MONOCROMÁTICA (PRETO / CINZA) ---
            java.awt.Color pretoPuro = java.awt.Color.BLACK;
            java.awt.Color cinzaEscuroGrafite = new java.awt.Color(74, 85, 104);  // #4A5568 - Excelente para cabeçalhos de tabelas
            java.awt.Color cinzaTextoMuted = new java.awt.Color(113, 128, 150);  // #718096 - Para subtítulos e datas
            java.awt.Color cinzaBorda = new java.awt.Color(204, 214, 224);       // #CCD6E0 - Linhas de grade sutis
            java.awt.Color cinzaFundoZebra = new java.awt.Color(247, 250, 252);   // #F7FAFC - Fundo zebrado bem suave
            java.awt.Color brancoPuro = java.awt.Color.WHITE;

            // --- 2. CONFIGURAÇÃO DE FONTES ---
            com.lowagie.text.Font fonteTitulo = com.lowagie.text.FontFactory.getFont(com.lowagie.text.FontFactory.HELVETICA_BOLD, 18, pretoPuro);
            com.lowagie.text.Font fonteSubtitulo = com.lowagie.text.FontFactory.getFont(com.lowagie.text.FontFactory.HELVETICA, 10, cinzaTextoMuted);
            com.lowagie.text.Font landmarkFont = com.lowagie.text.FontFactory.getFont(com.lowagie.text.FontFactory.HELVETICA_BOLD, 12, pretoPuro);
            com.lowagie.text.Font fonteCabecalhoTabela = com.lowagie.text.FontFactory.getFont(com.lowagie.text.FontFactory.HELVETICA_BOLD, 9, brancoPuro);
            com.lowagie.text.Font fonteLinhaTabela = com.lowagie.text.FontFactory.getFont(com.lowagie.text.FontFactory.HELVETICA, 9, pretoPuro);
            com.lowagie.text.Font fonteFiltroNegrito = com.lowagie.text.FontFactory.getFont(com.lowagie.text.FontFactory.HELVETICA_BOLD, 9, pretoPuro);
            com.lowagie.text.Font fonteTotal = com.lowagie.text.FontFactory.getFont(com.lowagie.text.FontFactory.HELVETICA_BOLD, 9, pretoPuro);

            // --- 3. CABEÇALHO DO RELATÓRIO ---
            com.lowagie.text.Paragraph titulo = new com.lowagie.text.Paragraph("FUNCIONÁRIOS POR EMPRESA", fonteTitulo);
            titulo.setAlignment(com.lowagie.text.Element.ALIGN_LEFT);
            documento.add(titulo);

            com.lowagie.text.Paragraph subtitulo = new com.lowagie.text.Paragraph("Projeto RH - Relatório Administrativo Operacional", fonteSubtitulo);
            subtitulo.setSpacingAfter(15);
            documento.add(subtitulo);

            // Linha divisória preta/cinza escura decorativa do cabeçalho geral
            com.lowagie.text.pdf.draw.LineSeparator linhaDivisoriaGeral = new com.lowagie.text.pdf.draw.LineSeparator();
            linhaDivisoriaGeral.setLineColor(cinzaEscuroGrafite);
            linhaDivisoriaGeral.setPercentage(100);
            linhaDivisoriaGeral.setOffset(-5);
            documento.add(linhaDivisoriaGeral);

            // --- 4. METADADOS E FILTROS NO TOPO ---
            com.lowagie.text.Paragraph metadados = new com.lowagie.text.Paragraph();
            metadados.setSpacingBefore(10);
            metadados.setSpacingAfter(20);
            metadados.add(new com.lowagie.text.Chunk("Filtro por Status: ", fonteSubtitulo));
            metadados.add(new com.lowagie.text.Chunk(statusFiltro + "       ", fonteFiltroNegrito));

            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("dd/MM/yyyy HH:mm");
            metadados.add(new com.lowagie.text.Chunk("Gerado em: " + sdf.format(new java.util.Date()), fonteSubtitulo));
            documento.add(metadados);

            // --- 5. CONSULTA AO BANCO DE DADOS POSTGRES ---
            StringBuilder interrogacoes = new StringBuilder();
            for (int i = 0; i < idsEmpresas.size(); i++) {
                interrogacoes.append("?");
                if (i < idsEmpresas.size() - 1) {
                    interrogacoes.append(",");
                }
            }

            String sql = "SELECT e.\"NOME_FANTASIA\" AS empresa_nome, f.\"NOME\", f.\"SETOR\", f.\"STATUS\" "
                    + "FROM \"Funcionarios\" f "
                    + "INNER JOIN \"Empresa\" e ON f.\"EMPRESA\" = e.\"NOME_FANTASIA\" "
                    + "WHERE f.\"STATUS\" = ? AND e.\"ID_EMPRESA\" IN (" + interrogacoes.toString() + ") "
                    + "ORDER BY e.\"NOME_FANTASIA\" ASC, f.\"SETOR\", f.\"NOME\" ASC";

            try ( Connection conn = ConexaoPostgres.conectar();  PreparedStatement pst = conn.prepareStatement(sql)) {

                pst.setString(1, statusFiltro);

                for (int i = 0; i < idsEmpresas.size(); i++) {
                    pst.setInt(i + 2, idsEmpresas.get(i));
                }

                try ( ResultSet rs = pst.executeQuery()) {
                    
                    String empresaAtual = "";
                    com.lowagie.text.pdf.PdfPTable tabela = null;
                    int totalFuncionariosEmpresa = 0;
                    boolean zebra = false;
                    int totalGeralRegistros = 0;

                    while (rs.next()) {
                        totalGeralRegistros++;
                        String empresaRow = rs.getString("empresa_nome");
                        String nome = rs.getString("NOME");
                        String setor = rs.getString("SETOR");
                        String status = rs.getString("STATUS");

                        // Controle de quebra e agrupamento por empresa
                        if (!empresaRow.equals(empresaAtual)) {
                            
                            // Se já havia uma tabela rodando, adiciona totais e renderiza antes da próxima empresa
                            if (tabela != null) {
                                adicionarLinhaTotal(tabela, totalFuncionariosEmpresa, fonteTotal, cinzaEscuroGrafite);
                                documento.add(tabela);
                                
                                // Pula rigorosamente as 3 linhas pedidas
                                com.lowagie.text.Paragraph espacamento = new com.lowagie.text.Paragraph("\n\n\n");
                                espacamento.setLeading(10.0f);
                                documento.add(espacamento);
                            }

                            // Reinicia contadores locais da nova empresa
                            empresaAtual = empresaRow;
                            totalFuncionariosEmpresa = 0;
                            zebra = false;

                            // Escreve o título da Empresa em PRETO Puro
                            com.lowagie.text.Paragraph tituloEmpresa = new com.lowagie.text.Paragraph("EMPRESA: " + empresaAtual.toUpperCase(), landmarkFont);
                            tituloEmpresa.setSpacingBefore(10);
                            tituloEmpresa.setSpacingAfter(8);
                            documento.add(tituloEmpresa);

                            // Inicializa tabela: Estrutura limpa de 3 colunas
                            tabela = new com.lowagie.text.pdf.PdfPTable(new float[]{5.0f, 3.0f, 2.0f});
                            tabela.setWidthPercentage(100);

                            // Cabeçalhos da tabela em Cinza Grafite Escuro com Letras Brancas (Contraste perfeito)
                            String[] cabecalhos = {"Nome do Funcionário", "Setor", "Status"};
                            for (String c : cabecalhos) {
                                com.lowagie.text.pdf.PdfPCell celulaCabecalho = new com.lowagie.text.pdf.PdfPCell(new com.lowagie.text.Paragraph(c, fonteCabecalhoTabela));
                                celulaCabecalho.setBackgroundColor(cinzaEscuroGrafite);
                                celulaCabecalho.setPadding(6);
                                celulaCabecalho.setHorizontalAlignment(com.lowagie.text.Element.ALIGN_LEFT);
                                tabela.addCell(celulaCabecalho);
                            }
                        }

                        totalFuncionariosEmpresa++;

                        // Montagem das células de dados
                        com.lowagie.text.pdf.PdfPCell cNome = new com.lowagie.text.pdf.PdfPCell(new com.lowagie.text.Paragraph(nome, fonteLinhaTabela));
                        com.lowagie.text.pdf.PdfPCell cSetor = new com.lowagie.text.pdf.PdfPCell(new com.lowagie.text.Paragraph(setor, fonteLinhaTabela));
                        com.lowagie.text.pdf.PdfPCell cStatus = new com.lowagie.text.pdf.PdfPCell(new com.lowagie.text.Paragraph(status, fonteLinhaTabela));

                        com.lowagie.text.pdf.PdfPCell[] linha = {cNome, cSetor, cStatus};
                        for (com.lowagie.text.pdf.PdfPCell cel : linha) {
                            cel.setPadding(5);
                            cel.setBorderColor(cinzaBorda);
                            if (zebra) {
                                cel.setBackgroundColor(cinzaFundoZebra); // Aplica o fundo cinza claro na linha zebrada
                            }
                        }

                        tabela.addCell(cNome);
                        tabela.addCell(cSetor);
                        tabela.addCell(cStatus);

                        zebra = !zebra;
                    }

                    // Insere a última empresa ao sair do laço
                    if (tabela != null) {
                        adicionarLinhaTotal(tabela, totalFuncionariosEmpresa, fonteTotal, cinzaEscuroGrafite);
                        documento.add(tabela);
                    }

                    // Validação de segurança para tabelas sem dados retornados
                    if (totalGeralRegistros == 0) {
                        com.lowagie.text.pdf.PdfPTable tabelaVazia = new com.lowagie.text.pdf.PdfPTable(1);
                        tabelaVazia.setWidthPercentage(100);
                        com.lowagie.text.pdf.PdfPCell celulaVazia = new com.lowagie.text.pdf.PdfPCell(new com.lowagie.text.Paragraph("Nenhum funcionário encontrado sob estes critérios.", fonteLinhaTabela));
                        celulaVazia.setPadding(12);
                        celulaVazia.setHorizontalAlignment(com.lowagie.text.Element.ALIGN_CENTER);
                        tabelaVazia.addCell(celulaVazia);
                        documento.add(tabelaVazia);
                    }
                }

            } catch (SQLException ex) {
                ex.printStackTrace();
                JOptionPane.showMessageDialog(this, "Erro de banco de dados ao processar relatório:\n" + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
                return;
            }

            JOptionPane.showMessageDialog(this, "Relatório gerado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            abrirPDFDoSistema(caminhoDestino);

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Erro ao gerar PDF:\n" + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        } finally {
            if (documento.isOpen()) {
                documento.close();
            }
        }
    }

    // Método auxiliar adaptado para o fechamento com traço em cinza escuro nítido
    private void adicionarLinhaTotal(com.lowagie.text.pdf.PdfPTable tabela, int total, com.lowagie.text.Font fonteTotal, java.awt.Color corLinha) {
        // Linha divisória horizontal sólida abaixo da última linha de dados
        com.lowagie.text.pdf.PdfPCell divisoria = new com.lowagie.text.pdf.PdfPCell();
        divisoria.setColspan(3);
        divisoria.setFixedHeight(1.2f);
        divisoria.setBorder(com.lowagie.text.Rectangle.TOP);
        divisoria.setBorderColor(corLinha); 
        tabela.addCell(divisoria);

        // Texto do Total
        com.lowagie.text.pdf.PdfPCell cTextoTotal = new com.lowagie.text.pdf.PdfPCell(new com.lowagie.text.Paragraph("Total de Funcionários Listados:", fonteTotal));
        cTextoTotal.setColspan(2);
        cTextoTotal.setPadding(6);
        cTextoTotal.setBorder(com.lowagie.text.Rectangle.NO_BORDER);
        cTextoTotal.setHorizontalAlignment(com.lowagie.text.Element.ALIGN_RIGHT);

        // Valor numérico totalizado
        com.lowagie.text.pdf.PdfPCell cNumeroTotal = new com.lowagie.text.pdf.PdfPCell(new com.lowagie.text.Paragraph(String.valueOf(total), fonteTotal));
        cNumeroTotal.setPadding(6);
        cNumeroTotal.setBorder(com.lowagie.text.Rectangle.NO_BORDER);
        cNumeroTotal.setHorizontalAlignment(com.lowagie.text.Element.ALIGN_LEFT);

        tabela.addCell(cTextoTotal);
        tabela.addCell(cNumeroTotal);
    }

    
    // Método auxiliar seguro para abrir o PDF no leitor padrão do Windows
    private void abrirPDFDoSistema(String caminhoDestino) {
    // Usamos uma Thread separada para que o processo do PDF não concorra com a interface do Java
    new Thread(() -> {
        try {
            java.io.File arquivo = new java.io.File(caminhoDestino);
            
            if (arquivo.exists()) {
                // Verifica se o Desktop é suportado pelo Sistema Operacional (Windows/Linux/Mac)
                if (java.awt.Desktop.isDesktopSupported()) {
                    java.awt.Desktop desktop = java.awt.Desktop.getDesktop();
                    
                    // Abre o arquivo de forma assíncrona e independente
                    desktop.open(arquivo);
                } else {
                    // Alternativa caso o Desktop do Java falhe por limitação do SO
                    Runtime.getRuntime().exec("cmd /c start \"\" \"" + caminhoDestino + "\"");
                }
            }
        } catch (Exception ex) {
            ex.printStackTrace();
            System.err.println("Não foi possível abrir o PDF automaticamente: " + ex.getMessage());
        }
    }).start();
}


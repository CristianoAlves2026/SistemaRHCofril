    private void carregarEmpresas() {
        // Modelo de tabela customizado para aceitar Boolean (Checkbox) na primeira coluna
        DefaultTableModel modelo = new DefaultTableModel(
                new Object[][]{},
                new String[]{"Selecionar", "ID", "Empresa"} // ID continua aqui internamente
        ) {
            Class[] types = new Class[]{
                java.lang.Boolean.class, java.lang.Integer.class, java.lang.String.class
            };
            boolean[] canEdit = new boolean[]{
                true, false, false // Apenas a coluna do Checkbox pode ser editada
            };

            @Override
            public Class getColumnClass(int columnIndex) {
                return types[columnIndex];
            }

            @Override
            public boolean isCellEditable(int rowIndex, int columnIndex) {
                return canEdit[columnIndex];
            }
        };

        jTableEmpresa.setModel(modelo);

        // --- TRUQUE PARA OCULTAR A COLUNA DO ID ---
        // Removemos a coluna ID (índice 1) da visualização da tabela, mas ela continua existindo no Modelo (dados)
        jTableEmpresa.getColumnModel().removeColumn(jTableEmpresa.getColumnModel().getColumn(1));

        // Ajusta a largura das colunas visíveis restantes
        jTableEmpresa.getColumnModel().getColumn(0).setPreferredWidth(80);  // Checkbox
        jTableEmpresa.getColumnModel().getColumn(1).setPreferredWidth(300); // Nome Fantasia (agora índice 1 visualmente)

        String sql = "SELECT \"ID_EMPRESA\", \"NOME_FANTASIA\" FROM \"Empresa\" ORDER BY \"NOME_FANTASIA\" ASC";
        

        try ( Connection conn = ConexaoPostgres.conectar();  PreparedStatement pst = conn.prepareStatement(sql);  ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {
                int id = rs.getInt("ID_EMPRESA");
                String nomeFantasia = rs.getString("NOME_FANTASIA");

                // Adiciona a linha normalmente: Checkbox desmarcado, ID, e o Nome da Empresa
                modelo.addRow(new Object[]{Boolean.FALSE, id, nomeFantasia});
            }

        } catch (SQLException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Erro ao carregar empresas:\n" + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }


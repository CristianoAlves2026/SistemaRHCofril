    private void carregarTabelaSetor() {

        String sql = "SELECT \"ID_SETOR\", \"NOME_SETOR\", \"ENCARREGADO\" "
                + "FROM \"Setor\" "
                + "ORDER BY UPPER(\"NOME_SETOR\")";

        javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
                new Object[][]{},
                new String[]{"ID", "SETOR", "ENCARREGADO"}
        ) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // 🔒 impede edição direta
            }
        };

        try ( java.sql.Connection conn = br.com.Conexao.ConexaoPostgres.conectar();  java.sql.PreparedStatement ps = conn.prepareStatement(sql);  java.sql.ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("ID_SETOR"),
                    rs.getString("NOME_SETOR"),
                    rs.getString("ENCARREGADO")
                });
            }

            jTableSetor.setModel(model);

            // 🔹 Ajuste de colunas
            jTableSetor.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_OFF);

            jTableSetor.getColumnModel().getColumn(0).setPreferredWidth(60);   // ID
            jTableSetor.getColumnModel().getColumn(1).setPreferredWidth(230);  // SETOR
            jTableSetor.getColumnModel().getColumn(2).setPreferredWidth(217);  // ENCARREGADO

            // 🔹 Melhorias visuais
            jTableSetor.getTableHeader().setReorderingAllowed(false);
            jTableSetor.setRowHeight(18);

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    private void carregarEncarregados() {

        String sql = "SELECT \"NOME\" "
                + "FROM \"Funcionarios\" "
                + "WHERE \"FUNCAO\" ILIKE '%ENC%' "
                + "AND UPPER(\"STATUS\") = 'ATIVO' "
                + "ORDER BY \"NOME\"";

        try ( java.sql.Connection conn = br.com.Conexao.ConexaoPostgres.conectar();  java.sql.PreparedStatement ps = conn.prepareStatement(sql);  java.sql.ResultSet rs = ps.executeQuery()) {

            jComboBoxEncarregado.removeAllItems();

            // 🔹 Item padrão
            jComboBoxEncarregado.addItem("Selecione o Encarregado");

            while (rs.next()) {
                jComboBoxEncarregado.addItem(rs.getString("NOME"));
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }


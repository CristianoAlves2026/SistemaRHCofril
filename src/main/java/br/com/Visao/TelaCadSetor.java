    private void jTableSetorMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableSetorMouseClicked
        int linha = jTableSetor.getSelectedRow();

        if (linha != -1) {

            Object id = jTableSetor.getValueAt(linha, 0);
            Object setor = jTableSetor.getValueAt(linha, 1);
            Object encarregado = jTableSetor.getValueAt(linha, 2);

            jTextFieldIDSetor.setText(id != null ? id.toString() : "");
            jTextFieldSetor.setText(setor != null ? setor.toString() : "");
            jComboBoxEncarregado.setSelectedItem(
                    encarregado != null ? encarregado.toString() : "Selecione o Encarregado"
            );
        }

    }//GEN-LAST:event_jTableSetorMouseClicked


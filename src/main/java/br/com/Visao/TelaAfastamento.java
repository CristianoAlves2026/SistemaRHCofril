    private void carregarTabelaAfastamentos() {

        try ( java.sql.Connection conn
                = br.com.Conexao.ConexaoPostgres.conectar()) {

            String sql = """
                     SELECT "ID",
                            "DATA_AFASTAMENTO",
                            "DATA_RETORNO",
                            "MOTIVO"
                     FROM "Afastados"
                     WHERE "ID_FUNC" = ?
                     ORDER BY "DATA_AFASTAMENTO" DESC
                     """;

            java.sql.PreparedStatement ps
                    = conn.prepareStatement(sql);

            ps.setInt(1, idFuncionario);

            java.sql.ResultSet rs = ps.executeQuery();

            // Sobrescrevemos o DefaultTableModel para retornar false em todas as células
            javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
                    new Object[]{
                        "ID",
                        "DATA AFASTAMENTO",
                        "DATA RETORNO",
                        "MOTIVO"
                    }, 0
            ) {
                @Override
                public boolean isCellEditable(int row, int column) {
                    return false; // Nenhuma célula poderá ser editada diretamente na tabela
                }
            };

            java.text.SimpleDateFormat sdf
                    = new java.text.SimpleDateFormat("dd/MM/yyyy");

            while (rs.next()) {

                java.sql.Date dataAfast
                        = rs.getDate("DATA_AFASTAMENTO");

                java.sql.Date dataRet
                        = rs.getDate("DATA_RETORNO");

                modelo.addRow(new Object[]{
                    rs.getInt("ID"),
                    dataAfast != null
                    ? sdf.format(dataAfast)
                    : "",
                    dataRet != null
                    ? sdf.format(dataRet)
                    : "",
                    rs.getString("MOTIVO")

                });

            }

            jTableMotivoAfastamento.setModel(modelo);
            ajustarColunasTabela();

        } catch (Exception e) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Erro ao carregar afastamentos:\n" + e.getMessage()
            );

        }

    }


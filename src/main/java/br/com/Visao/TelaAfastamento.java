    private void jTableMotivoAfastamentoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableMotivoAfastamentoMouseClicked
        int linha = jTableMotivoAfastamento.getSelectedRow();

        if (linha == -1) {
            return;
        }

        // Pega o ID da linha selecionada
        idAfastamentoSelecionado = (Integer) jTableMotivoAfastamento.getValueAt(linha, 0);

        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("dd/MM/yyyy");

        // 1. Preenche Data de Afastamento
        try {
            Object valAfast = jTableMotivoAfastamento.getValueAt(linha, 1);
            if (valAfast != null && !valAfast.toString().trim().isEmpty()) {
                jDateChooserAfastamento.setDate(sdf.parse(valAfast.toString()));
            } else {
                jDateChooserAfastamento.setDate(null);
            }
        } catch (Exception e) {
            jDateChooserAfastamento.setDate(null);
        }

        // 2. Preenche Data de Retorno (CORRIGIDO)
        try {
            Object valRetorno = jTableMotivoAfastamento.getValueAt(linha, 2);
            if (valRetorno != null && !valRetorno.toString().trim().isEmpty()) {
                // Se a string NÃO estiver vazia, faz o parse para a Date do JDateChooser
                jDateChooserRetorno.setDate(sdf.parse(valRetorno.toString()));
            } else {
                // Se estiver vazia ou null, define como null
                jDateChooserRetorno.setDate(null);
            }
        } catch (Exception e) {
            jDateChooserRetorno.setDate(null);
        }

        // 3. Preenche Motivo
        Object motivoObj = jTableMotivoAfastamento.getValueAt(linha, 3);
        jTextPaneMotivo.setText(motivoObj != null ? motivoObj.toString() : "");


    }//GEN-LAST:event_jTableMotivoAfastamentoMouseClicked

    private void jButtonSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSalvarActionPerformed
        // --- LÓGICA DE EXCLUSÃO ---
        if (jRadioExcluir.isSelected()) {

            if (idAfastamentoSelecionado == null) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Selecione um afastamento na tabela para excluir.",
                        "Atenção",
                        javax.swing.JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            int opcao = javax.swing.JOptionPane.showConfirmDialog(
                    this,
                    "Confirma exclusão do afastamento selecionado?",
                    "Confirmar Exclusão",
                    javax.swing.JOptionPane.YES_NO_OPTION,
                    javax.swing.JOptionPane.QUESTION_MESSAGE
            );

            if (opcao == javax.swing.JOptionPane.YES_OPTION) {

                String sql = """
                         DELETE FROM "Afastados"
                         WHERE "ID" = ?
                         """;

                try ( java.sql.Connection conn = br.com.Conexao.ConexaoPostgres.conectar();  java.sql.PreparedStatement ps = conn.prepareStatement(sql)) {

                    ps.setInt(1, idAfastamentoSelecionado);
                    ps.executeUpdate();

                    javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "Afastamento excluído com Sucesso!"
                    );

                    carregarTabelaAfastamentos();
                    limparCampos();
                    idAfastamentoSelecionado = null;

                } catch (Exception e) {
                    javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "Erro ao excluir afastamento:\n" + e.getMessage(),
                            "Erro",
                            javax.swing.JOptionPane.ERROR_MESSAGE
                    );
                }
            }
            return; // Finaliza a execução para não cair nas validações de inserção/edição
        }

        // --- LÓGICA DE NOVO / EDITAR ---
        if (jDateChooserAfastamento.getDate() == null) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Informe a data de afastamento."
            );
            return;
        }

        java.sql.Date dataAfastamento = new java.sql.Date(
                jDateChooserAfastamento.getDate().getTime()
        );

        java.sql.Date dataRetorno = null;
        if (jDateChooserRetorno.getDate() != null) {
            dataRetorno = new java.sql.Date(jDateChooserRetorno.getDate().getTime());
        }

        String motivo = jTextPaneMotivo.getText();

        try ( java.sql.Connection conn = br.com.Conexao.ConexaoPostgres.conectar()) {

            if (jRadioButtonNovo.isSelected()) {

                String sql = """
                         INSERT INTO "Afastados"
                         ("ID_FUNC", "DATA_AFASTAMENTO", "DATA_RETORNO", "MOTIVO")
                         VALUES (?, ?, ?, ?)
                         """;

                java.sql.PreparedStatement ps = conn.prepareStatement(sql);
                ps.setInt(1, idFuncionario);
                ps.setDate(2, dataAfastamento);
                ps.setDate(3, dataRetorno);
                ps.setString(4, motivo);

                ps.executeUpdate();

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Afastamento registrado com sucesso."
                );

            } else if (jRadioEditar.isSelected()) {

                if (idAfastamentoSelecionado == null) {
                    javax.swing.JOptionPane.showMessageDialog(
                            this,
                            "Selecione um afastamento na tabela."
                    );
                    return;
                }

                String sql = """
                         UPDATE "Afastados"
                         SET "DATA_AFASTAMENTO" = ?,
                             "DATA_RETORNO" = ?,
                             "MOTIVO" = ?
                         WHERE "ID" = ?
                         """;

                java.sql.PreparedStatement ps = conn.prepareStatement(sql);
                ps.setDate(1, dataAfastamento);
                ps.setDate(2, dataRetorno);
                ps.setString(3, motivo);
                ps.setInt(4, idAfastamentoSelecionado);

                ps.executeUpdate();

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Afastamento atualizado com sucesso."
                );

            } else {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Selecione a opção 'Novo', 'Editar' ou 'Excluir'."
                );
                return;
            }

            carregarTabelaAfastamentos();
            limparCampos();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Erro ao salvar:\n" + e.getMessage()
            );
        }

    }//GEN-LAST:event_jButtonSalvarActionPerformed


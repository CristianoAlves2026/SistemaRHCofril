    private void carregarTabelaFuncao() {

    String sql = "SELECT \"ID_FUNCAO\", \"NOME_FUNCAO\" "
            + "FROM \"Funcao\" "
            + "ORDER BY UPPER(\"NOME_FUNCAO\")";

    javax.swing.table.DefaultTableModel model = new javax.swing.table.DefaultTableModel(
            new Object[][]{},
            new String[]{"ID", "FUNÇÃO"}
    ) {
        @Override
        public boolean isCellEditable(int row, int column) {
            return false; // 🔒 impede edição direta
        }
    };

    try (java.sql.Connection conn = br.com.Conexao.ConexaoPostgres.conectar();
         java.sql.PreparedStatement ps = conn.prepareStatement(sql);
         java.sql.ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("ID_FUNCAO"),
                rs.getString("NOME_FUNCAO")
            });
        }

        jTableFuncao.setModel(model);

        // 🔹 Ajuste de colunas
        jTableFuncao.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_OFF);

        jTableFuncao.getColumnModel().getColumn(0).setPreferredWidth(60);   // ID
        jTableFuncao.getColumnModel().getColumn(1).setPreferredWidth(410);  // FUNCAO

        // 🔹 Melhorias visuais
        jTableFuncao.getTableHeader().setReorderingAllowed(false);
        jTableFuncao.setRowHeight(18);

    } catch (Exception e) {
        e.printStackTrace();
    }
}
    


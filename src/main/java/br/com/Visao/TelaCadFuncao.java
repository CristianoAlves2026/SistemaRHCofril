    private void jTableFuncaoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableFuncaoMouseClicked
      int linha = jTableFuncao.getSelectedRow();

        if (linha != -1) {

            Object id = jTableFuncao.getValueAt(linha, 0);
            Object funcao = jTableFuncao.getValueAt(linha, 1);

            jTextFieldIDSetor.setText(id != null ? id.toString() : "");
            jTextFieldFuncao.setText(funcao != null ? funcao.toString() : "");
        } 
    }//GEN-LAST:event_jTableFuncaoMouseClicked

    private void jButtonSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSalvarActionPerformed
     if (!jRadioButtonNovo.isSelected() && !jRadioEditar.isSelected()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione uma opção antes de salvar.");
            return;
        }

        String funcao = jTextFieldFuncao.getText().trim();

        // Validação da função (obrigatória)
        if (funcao.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Informe a Função");
            jTextFieldFuncao.requestFocus();
            return;
        }

        try (java.sql.Connection conn = br.com.Conexao.ConexaoPostgres.conectar()) {

            String sql;

            // NOVO
            if (jRadioButtonNovo.isSelected()) {
                sql = "INSERT INTO \"Funcao\" (\"NOME_FUNCAO\") VALUES (?)";
            } 
            // EDITAR
            else if (jRadioEditar.isSelected()) {

                if (jTextFieldIDSetor.getText().isEmpty()) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Selecione um registro para editar");
                    return;
                }

                sql = "UPDATE \"Funcao\" SET \"NOME_FUNCAO\"=? WHERE \"ID_FUNCAO\"=?";
            } else {
                javax.swing.JOptionPane.showMessageDialog(this, "Selecione Novo ou Editar");
                return;
            }

            try (java.sql.PreparedStatement ps = conn.prepareStatement(sql)) {

                ps.setString(1, funcao);

                // Se for editar, seta o ID
                if (jRadioEditar.isSelected()) {
                    ps.setInt(2, Integer.parseInt(jTextFieldIDSetor.getText()));
                }

                ps.executeUpdate();

                javax.swing.JOptionPane.showMessageDialog(this, "Salvo com sucesso!");
                
                // Limpeza e reset da tela
                jTextFieldIDSetor.setText("");
                jTextFieldFuncao.setText("");
                jRadioButtonNovo.setSelected(false);
                jRadioEditar.setSelected(false);
                carregarTabelaFuncao();

            }

        } catch (Exception e) {
            e.printStackTrace();
        }  
    }//GEN-LAST:event_jButtonSalvarActionPerformed

